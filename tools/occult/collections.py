def ctx_services(ix):
    life = ix.resolve("section:lifestyle-expenses").entity
    if life is None:
        rest = passthrough(ix, "section:services")
        return dict(title="Services", counts=[plural(len(rest), "table")], sections=rest)
    rows = []
    for c in life.children:
        m = re.match(r"^(.*?) \((.*)\)$", c.title)
        name, cost = (m.group(1), m.group(2)) if m else (c.title, "")
        rows.append([code(c.sid), name, cost, pg(c)])
    lifestyle = sec(life.title, tbl(["id", "lifestyle", "cost", "p."], rows), count=len(rows), sid=life.sid, page=plabel(life))
    rest = passthrough(ix, "section:services")
    return dict(title="Services", counts=[plural(1 + len(rest), "table")], sections=[lifestyle, *rest])


