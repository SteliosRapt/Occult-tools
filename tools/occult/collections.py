def book_label(b):
    """`PHB 2024`, `EFA 2025`: a book's name on the counts line."""
    return f"{data.book_abbr(b['short'])} {b.get('edition') or ''}".rstrip()


def header(ix, digest):
    """Line 1 of every file: the data folders read and the inputs hash."""
    return HEADER.format(", ".join(f"data/{b['id']}" for b in ix.books), digest)


def source(ix, books):
    """`source: PHB 2024`, or `sources: PHB 2024, EFA 2025`, for the books a file's rows come from."""
    names = [book_label(b) for b in ix.books if b["short"] in books] or [book_label(ix.books[0])]
    return ("sources: " if len(names) > 1 else "source: ") + ", ".join(names)


ID = re.compile(r"`([a-z-]+:[a-z0-9][a-z0-9/+-]*)`")


def books_of(ix, s):
    """The books of every entity id quoted in a rendered file."""
    return {ix.by_sid[m].book for m in ID.findall(s) if m in ix.by_sid}


