    cols = item_cols("ability", "utilize", "craft")
    row = lambda e: [code(e.sid), e.title, dash(e.data.get("ability")), dash(e.data.get("utilize")),
                     dash(e.data.get("craft")), *item_tail(e)]
    groups = [sec(cat, tbl(cols, [row(e) for e in g]), count=len(g)) for cat, g in by(tools, lambda e: e.data["category"])]
