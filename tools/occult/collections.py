def ctx_magic_items_by_rarity(ix):
    """One section per rarity; an entry whose variants differ (rarity Varies) is listed under each of
    its variants' rarities, naming those variants."""
    ms = magic_items(ix)
    cols = ["id", "name", "category", "attunement", "variants", "p."]
    groups = {r: [] for r in RARITIES + ["Varies"]}
    for e in ms:
        d, vs = e.data, e.data.get("variants") or []
        own = d.get("rarity")
        if own in RARITIES:
            groups[own].append((e, "—"))
        for r in RARITIES:
            names = [v["title"] for v in vs if v.get("rarity") == r]
            if names and own != r:
                groups[r].append((e, "; ".join(names)))
        if own not in RARITIES and not any(v.get("rarity") in RARITIES for v in vs):
            groups["Varies"].append((e, "—"))
    secs = [sec(r, tbl(cols, [[code(e.sid), e.title, dash(e.data.get("category")), attune(e.data.get("attunement")), v, pg(e)]
                              for e, v in g]), count=len(g)) for r, g in groups.items() if g]
    return dict(title="Magic items by rarity", counts=[plural(len(ms), "magic item"), plural(len(secs), "rarity", "rarities")],
                sections=secs)


# ---------------------------------------------------------------- rules chapters of other books
PROSE = ("chapter", "section")


def pure(e):
    """A section whose subtree is only sections (no class, spell, item, ... inside): rules prose."""
    return e.type == "section" and all(pure(c) for c in e.children)


def rules_sections(e, depth):
    body = "\n\n".join(text.blocks_md([b for b in e.content if b["type"] != "caption"]))
    return sec(e.title, sid=e.sid, page=plabel(e), body=body or None,
               sections=[rules_sections(c, depth + 1) for c in e.children])


def rules_chapters(ix):
    """[(book, chapter, [top sections])]: for each book after the PHB, every chapter holding rules prose
    (sections outside classes, species, items ...). The PHB's rules are its own book; here only
    conditions and actions are collected from it."""
    out = []
    for root in ix.roots:
        if root.book == "phb" or root.type != "chapter":
            continue
        tops = []

        def walk(e):
            for c in e.children:
                if pure(c) and (c.content or c.children):
                    tops.append(c)
                elif c.type in PROSE:
                    walk(c)
        walk(root)
        if tops:
            out.append((root, tops))
    return out


def chapter_name(e):
    return re.sub(r"^(Chapter \d+|Appendix \w*):\s*", "", e.title)


def ctx_rules_chapter(ix, ch, tops):
    n = sum(1 for t in tops for _ in walk_all(t))
    return dict(title=f"{chapter_name(ch)} ({data.book_abbr(ch.book)})", sid=ch.sid, chapter=ch.title,
                counts=[plural(n, "section")], sections=[rules_sections(t, 2) for t in tops])


def walk_all(e):
    yield e
    for c in e.children:
        yield from walk_all(c)


