def core_traits(e):
    d = e.data
    ct, sc = d["core_traits"], d.get("spellcasting")
    rows = [["Primary ability", ct["primary_ability"]],
            ["Hit point die", ct["hit_point_die"]],
            ["Saving throws", ", ".join(ct["saving_throw_proficiencies"])],
            ["Skills", ct["skill_proficiencies"]["text"]],
            ["Weapons", dash(ct["weapon_proficiencies"])],
            ["Armor training", dash(ct["armor_training"]["text"])],
            ["Tools", dash(ct["tool_proficiencies"])],
            ["Starting equipment", ct["starting_equipment"]],
            ["Subclass", f"Level {d['subclass_level']}"]]
    if sc:
        rows.append(["Spellcasting", f"{'Pact Magic' if sc['kind'] == 'pact' else 'Spellcasting'} ({sc['ability']})"
                     + (", prepares spells" if sc.get("prepares_spells") else "")])
    return tbl(["trait", "details"], rows)


def progression(e):
    from .views.klass import progression_md    # the `show class:*` renderer
    return progression_md(e.data).split("\n", 1)[1]


def feature_table(fs):
    return tbl(["id", "feature", "lvl", "p."], [[code(e.sid), e.title, e.data.get("level"), pg(e)] for e in fs])


def ctx_class(ix, e):
    cls = e.title.lower()
    feats = query.select(ix, "feature", {"class": cls})
    own = sorted((f for f in feats if f.owner_subclass is None), key=lambda f: (f.data["level"], f.order))
    subs = []
    for s in query.select(ix, "subclass", {"class": cls}):
        sf = sorted((f for f in feats if f.owner_subclass is s), key=lambda f: (f.data["level"], f.order))
        subs.append(sec(s.title, feature_table(sf), count=len(sf), sid=s.sid, page=plabel(s), note=s.data.get("tagline")))
    opts = [sec(p.title, tbl(["id", "option", "p."], [[code(o.sid), o.title, pg(o)] for o in g]), count=len(g),
                sid=p.sid, page=plabel(p))
            for p, g in by([o for o in ix.all("option") if o.owner_class == cls], lambda o: o.parent)]
    sections = [sec("Core traits", core_traits(e)),
                sec("Level progression", body=progression(e)),
                sec("Class features", feature_table(own), count=len(own)),
                sec("Subclasses", sections=subs, count=len(subs))]
    if opts:
        sections.append(sec("Options", sections=opts, count=sum(o["count"] for o in opts)))
    nsub = sum(s["count"] for s in subs)
    return dict(title=e.title, sid=e.sid, page=plabel(e), tagline=e.data["tagline"], spells=e.data.get("has_spell_list") or bool(e.data.get("spell_list")),
                counts=[f"Hit die d{e.data['core_traits']['hit_die']}", plural(len(subs), "subclass", "subclasses"),
                        plural(len(own), "class feature"), plural(nsub, "subclass feature"),
                        plural(sum(o["count"] for o in opts), "option") if opts else ""],
                sections=sections)


