RARITIES = ["Common", "Uncommon", "Rare", "Very Rare", "Legendary", "Artifact"]


def attune(a):
    return "—" if not a else "yes" if a is True else a


def charges(d):
    n, r = d.get("charges"), d.get("recharge")
    return dash(" · ".join(str(x) for x in (n, r and f"recharge: {r}") if x))


