# ---------------------------------------------------------------- inputs hash
# The code that shapes the .md output: this module and what it imports, transitively (a test
# checks the list against the imports). Render-only code (pipeline, cards, books) is left out,
# so editing it does not stale every collection.
CODE = ["__init__.py", "collections.py", "data.py", "query.py", "text.py", "types.py", "views/klass.py"]

def input_paths():
    """Every file the output depends on, in a fixed order."""
    paths = sorted(DATA_ROOT.glob("*/*.json"))
    paths += [ROOT / "tools" / "occult" / m for m in CODE]
    paths += sorted(p for p in TEMPLATES.rglob("*") if p.is_file())
    return paths


def inputs_hash():
    """sha256 over (relative path, bytes) of input_paths(), 12 hex digits."""
    h = hashlib.sha256()
    for p in input_paths():
        try:
            name = p.relative_to(ROOT).as_posix()
        except ValueError:
            name = "data/" + p.relative_to(DATA_ROOT).as_posix()
        h.update(name.encode() + b"\0")
        h.update(p.read_bytes() + b"\0")
    return h.hexdigest()[:12]


# ---------------------------------------------------------------- small helpers
def tbl(cols, rows):
    return {"cols": cols, "rows": rows}


def sec(title, table=None, *, count=None, sid=None, page=None, note=None, body=None, sections=()):
    """One `##` section; nested `sections` render one heading level deeper."""
    return dict(title=title, table=table, count=count, sid=sid, page=page, note=note, body=body, sections=list(sections))


def pg(e):
    """A table's `p.` cell: `274` for the PHB; another book's entity carries its book (`MM 12`, `FRHoF 30`; only the book when it prints no page)."""
    if e.book == "phb":
        return e.page if e.page is not None else data.book_abbr(e.book)
    return f"{data.book_abbr(e.book)} {e.page}" if e.page is not None else data.book_abbr(e.book)


def plabel(e, page=None):
    """A section line's page: `p.274`, `EFA p.21`, `DMG` (no printed page: Appendix C) or None."""
    page = page if page is not None else e.page
    p = f"p.{page}" if page is not None else ""
    return (p or data.book_abbr(e.book)) if e.book == "phb" else f"{data.book_abbr(e.book)} {p}".rstrip()


def code(sid):
    return f"`{sid}`"


def num(x):
    """cost_gp / weight_lb for sorting: 0.1, 2, 1.5; blank when unknown."""
    return "" if x is None else f"{x:g}"


def dash(x):
    return "—" if x in (None, "", []) else str(x)


def level_name(n):
    return "Cantrips" if n == 0 else f"Level {n}"


def level_short(n):
    return "cantrip" if n == 0 else str(n)


def plural(n, word, many=None):
    return f"{n} {word if n == 1 else many or word + 's'}"


def counts(*bits):
    return " · ".join(b for b in bits if b)


def by(items, key):
    """Group items by key, keeping first-seen order: [(key, [items])]."""
    out = {}
    for x in items:
        out.setdefault(key(x), []).append(x)
    return list(out.items())


def passthrough(ix, root_sid):
    """Tables that exist only as `table` blocks under a section (mounts, services): one section each."""
    out = []

    def walk(e):
        for b in e.content:
            if b["type"] == "table":
                out.append(sec(b.get("title") or e.title, tbl(b["columns"], b["rows"]), sid=e.sid,
                               page=plabel(e, b.get("page"))))
        for c in e.children:
            walk(c)
    root = ix.resolve(root_sid).entity
    if root:
        walk(root)
    return out


