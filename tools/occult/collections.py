def environment():
    import jinja2                                   # the only third-party import, and only on the make path
    env = jinja2.Environment(loader=jinja2.FileSystemLoader(str(TEMPLATES)), undefined=jinja2.StrictUndefined,
                             trim_blocks=True, lstrip_blocks=True, keep_trailing_newline=True, autoescape=False)
    env.globals["table"] = lambda t: text.md_table(t["cols"], t["rows"])
    return env


def finish(s, head):
    """Header line, LF only, no trailing spaces, single blank lines, one trailing newline."""
    lines = [ln.rstrip() for ln in s.replace("\r\n", "\n").split("\n")]
    body = re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip("\n")
    return head + "\n" + body + "\n"


SOURCE_SLOT = "\x00source\x00"      # filled in after rendering, from the ids the file quotes
GROUPS = {"": "Character options and creatures", "magic-items": "Magic items"}


def build(ix):
    """Render every collection in memory: {relpath: Doc}, in catalogue order (README.md last)."""
    env, head = environment(), header(ix, inputs_hash())
    docs, used = {}, set()
    for path, template, ctx in catalogue(ix):
        stats = counts(*ctx["counts"])
        out = env.get_template(template).render(**dict(ctx, counts=counts(stats, SOURCE_SLOT)))
        books = books_of(ix, out)
        used |= books
        docs[path] = Doc(finish(out.replace(SOURCE_SLOT, source(ix, books)), head), ctx["title"], stats)
    groups = by(docs.items(), lambda kv: kv[0].split("/")[0] if "/" in kv[0] else "")
    index = [dict(title=GROUPS.get(g, g.title()),
                  rows=[[f"[{p}]({p})", d.title, d.stats] for p, d in items]) for g, items in groups]
    index.sort(key=lambda g: g["title"] == GROUPS[""])
    readme = dict(title="Collections", counts=counts(plural(len(docs), "file"), source(ix, used)),
                  folders=", ".join(f"`data/{b['id']}`" for b in ix.books),
                  groups=[sec(g["title"], tbl(["file", "title", "contents"], g["rows"]), count=len(g["rows"])) for g in index])
    docs["README.md"] = Doc(finish(env.get_template("readme.md.j2").render(**readme), head), readme["title"],
                            plural(len(docs), "file"))
    return docs


# ---------------------------------------------------------------- disk
def on_disk(root):
    root = Path(root)
    return sorted(p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()) if root.is_dir() else []


def check(docs, root=OUT):
    """[(kind, relpath)] where kind is stale, missing or extra; empty when the tree matches."""
    root = Path(root)
    out = []
    for path, doc in docs.items():
        p = root / path
        if not p.is_file():
            out.append(("missing", path))
        elif p.read_bytes() != doc.text.encode("utf-8"):
            out.append(("stale", path))
    out += [("extra", p) for p in on_disk(root) if p not in docs]
    return sorted(out, key=lambda x: (x[1], x[0]))


def is_generated(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.readline().startswith(HEADER_PREFIX)
    except (OSError, UnicodeDecodeError):
        return False


def write(docs, root=OUT):
    """Write changed files; remove generated files the catalogue no longer has. -> [(relpath, status)]."""
    root = Path(root)
    out = []
    for path, doc in docs.items():
        p = root / path
        raw = doc.text.encode("utf-8")
        if p.is_file() and p.read_bytes() == raw:
            out.append((path, "unchanged"))
            continue
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(raw)
        out.append((path, "written"))
    for path in on_disk(root):
        if path not in docs:
            if is_generated(root / path):
                (root / path).unlink()
                out.append((path, "removed"))
            else:
                out.append((path, "kept (not generated; remove it by hand)"))
    for d in sorted((d for d in root.rglob("*") if d.is_dir()), key=lambda d: -len(d.parts)):
        if not any(d.iterdir()):
            d.rmdir()
    return out
